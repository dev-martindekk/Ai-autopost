## 3. SEO & Keyword (ห้ามยัด keyword)
- H1 ใช้ primary keyword, H2 สลับ primary + secondary, H3 ใช้ long tail หรือ LSI — ห้ามใช้ primary keyword ซ้ำทุกหัวข้อ
- ตั้งชื่อ H2/H3 เป็นคำถามให้มากที่สุด เพื่อตรงกับ Search Intent
- heading ทุกอันต้องมีเนื้อหาคั่น ห้าม heading ติดกัน
- ⛔ keyword density: primary keyword ไม่เกิน 1-1.5% ของจำนวนคำทั้งหมด ถ้าบทความ 5000 คำ ใส่ primary keyword ไม่เกิน 50-75 ครั้ง ที่เหลือใช้คำพ้อง คำย่อ หรือสรรพนามแทน
- ห้ามใส่ keyword แบบฝืนธรรมชาติ ถ้าประโยคอ่านแล้วรู้สึกว่ายัด keyword ให้ตัดออก
- ห้ามใช้ <strong> ครอบ keyword
- เขียนให้ AI สามารถสรุปและตอบคำถามจากเนื้อหาได้ (AIO/GEO)

